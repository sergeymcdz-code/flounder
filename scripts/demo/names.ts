export function fullName(index: number, gender: string, expanded = false) {
  const female = gender === 'F';
  const names = female ? femaleNames : maleNames;
  // Preserve S02 identities when the calendar pools grow.
  return { lastName: surnames[index % (expanded ? surnames.length : 120)] + (female ? 'а' : ''),
    firstName: names[Math.floor(index / 2) % (expanded ? names.length : 48)],
    middleName: patronymics[(Math.floor(index / 2) + Math.floor(index / 16)) % patronymics.length][female ? 1 : 0] };
}
