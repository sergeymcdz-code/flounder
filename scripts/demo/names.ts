export function fullName(index: number, gender: string) {
  const female = gender === 'F';
  const names = female ? femaleNames : maleNames;
  return { lastName: surnames[index % surnames.length] + (female ? 'а' : ''),
    firstName: names[Math.floor(index / 2) % names.length],
    middleName: patronymics[(Math.floor(index / 2) + Math.floor(index / 16)) % patronymics.length][female ? 1 : 0] };
}
